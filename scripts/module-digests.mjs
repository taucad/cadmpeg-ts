// The identity of every WebAssembly module a release ships (engine delivery
// charter D6, D8): `cadmpeg-ts/digests` states each packed `<id>_bg.wasm` and
// the `<id>_bg.wasm.gz` attached to the version's GitHub Release, so a host
// that fetches a module from anywhere can verify it before instantiation.
//
// Everything here reads and writes the built bytes only, and imports nothing
// but Node builtins: validate-pack runs it inside the frozen release tree, and
// the release-assets job installs no dependencies.

import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { gunzipSync, gzipSync } from 'node:zlib';

import { MODULES } from './package-files.mjs';

/** The gzip header's OS byte (RFC 1952 §2.3.1): 3 is Unix, as `gzip -n` writes it on Linux. */
const GZIP_OS_UNIX = 3;

/**
 * Compress one module deterministically: zlib level 9, no file name, a zero
 * modification time, and the OS byte fixed to Unix so the header does not
 * depend on the platform zlib was compiled for. The assemble job builds each
 * file once and the digest map names exactly those bytes; nothing rebuilds it.
 *
 * @param {Uint8Array} bytes - The module.
 * @returns {Buffer} The gzip member.
 */
export const gzipModule = (bytes) => {
  const gzip = gzipSync(bytes, { level: 9 });
  // zlib writes a bare header: magic, CM=8, FLG=0 (no name, comment or extra
  // field), MTIME=0, XFL=2 at level 9. Refuse anything else rather than ship
  // a header that could carry a time or a path.
  if (gzip[0] !== 0x1f || gzip[1] !== 0x8b || gzip[2] !== 8 || gzip[3] !== 0 || gzip.readUInt32LE(4) !== 0) {
    throw new Error('zlib wrote a gzip header with a name, flags or a modification time');
  }
  gzip[9] = GZIP_OS_UNIX;
  return gzip;
};

/**
 * @param {Uint8Array} bytes - File contents.
 * @returns {{ sha256: string, byteLength: number }} Lowercase hex SHA-256 and length.
 */
export const describeFile = (bytes) => ({
  sha256: createHash('sha256').update(bytes).digest('hex'),
  byteLength: bytes.byteLength,
});

const DECLARATIONS = `import type { ModuleId } from './formats.mjs';

/** The SHA-256 (lowercase hex) and byte length of one file. */
export type FileDigest = {
  readonly sha256: string;
  readonly byteLength: number;
};

/** One WebAssembly module, as packed and as attached to the GitHub Release. */
export type ModuleDigest = {
  /** \`cadmpeg-ts/wasm/<id>_bg.wasm\` in this package. */
  readonly wasm: FileDigest;
  /** \`<id>_bg.wasm.gz\` on this version's GitHub Release; it decompresses to \`wasm\`. */
  readonly gzip: FileDigest;
};

/**
 * Every module's digest, generated from the built bytes when the release was
 * assembled. Verify a module fetched from any host against it before use.
 */
export declare const digests: Readonly<Record<ModuleId, ModuleDigest>>;
`;

/**
 * Render `dist/digests.mjs`.
 *
 * @param {Record<string, { wasm: object, gzip: object }>} digests - The map.
 * @returns {string} The module source.
 */
export const renderDigestsModule = (digests) =>
  `// Generated by scripts/module-digests.mjs from the built modules. Do not edit.\n` +
  `const file = (sha256, byteLength) => Object.freeze({ sha256, byteLength });\n` +
  `export const digests = Object.freeze({\n` +
  Object.entries(digests)
    .map(
      ([id, { wasm, gzip }]) =>
        `  ${id}: Object.freeze({ wasm: file('${wasm.sha256}', ${wasm.byteLength}), gzip: file('${gzip.sha256}', ${gzip.byteLength}) }),\n`,
    )
    .join('') +
  `});\n`;

/**
 * Compress every packed module into `assetsDir` and write the digest map
 * beside the package's other entries. The map and the assets come from the
 * same bytes in one pass.
 *
 * @param {{ distDir: string, assetsDir: string }} paths - Package `dist/` and the release asset directory.
 * @returns {Record<string, { wasm: object, gzip: object }>} The map written.
 */
export const writeModuleDigests = ({ distDir, assetsDir }) => {
  rmSync(assetsDir, { force: true, recursive: true });
  mkdirSync(assetsDir, { recursive: true });
  /** @type {Record<string, { wasm: object, gzip: object }>} */
  const digests = {};
  const sums = [];
  for (const id of MODULES) {
    const wasm = readFileSync(join(distDir, 'wasm', `${id}_bg.wasm`));
    const gzip = gzipModule(wasm);
    writeFileSync(join(assetsDir, `${id}_bg.wasm.gz`), gzip);
    digests[id] = { wasm: describeFile(wasm), gzip: describeFile(gzip) };
    sums.push(`${digests[id].gzip.sha256}  ${id}_bg.wasm.gz\n`);
  }
  writeFileSync(join(assetsDir, 'SHA256SUMS'), sums.join(''));
  writeFileSync(join(distDir, 'digests.mjs'), renderDigestsModule(digests));
  writeFileSync(join(distDir, 'digests.d.mts'), DECLARATIONS);
  return digests;
};

/**
 * Load a package's generated digest map.
 *
 * @param {string} packageDir - Package root.
 * @returns {Promise<Record<string, { wasm: { sha256: string, byteLength: number }, gzip: { sha256: string, byteLength: number } }>>} The map.
 */
export const readDigests = async (packageDir) =>
  (await import(pathToFileURL(join(packageDir, 'dist/digests.mjs')).href)).digests;

const same = (left, right) => left?.sha256 === right.sha256 && left?.byteLength === right.byteLength;

/**
 * Compare the map with the packed modules: exactly one entry per module, and
 * each `wasm` digest equal to the file in `dist/wasm/`.
 *
 * @param {object} digests - The map.
 * @param {string} packageDir - Package root.
 * @returns {string[]} One finding per mismatch; empty when they agree.
 */
export const packedModuleFindings = (digests, packageDir) => {
  const findings = [];
  const ids = Object.keys(digests ?? {}).sort();
  if (ids.join() !== [...MODULES].sort().join()) {
    findings.push(`the digest map names [${ids.join(', ')}], expected [${[...MODULES].sort().join(', ')}]`);
  }
  for (const id of MODULES) {
    const packed = describeFile(readFileSync(join(packageDir, 'dist/wasm', `${id}_bg.wasm`)));
    if (!same(digests?.[id]?.wasm, packed)) {
      findings.push(
        `${id}: the map states ${JSON.stringify(digests?.[id]?.wasm)}, the packed ${id}_bg.wasm is ${JSON.stringify(packed)}`,
      );
    }
  }
  return findings;
};

/**
 * Compare a directory of release assets with the map: exactly the thirteen
 * `<id>_bg.wasm.gz` files, each equal to its `gzip` digest, and each
 * decompressing to the module its `wasm` digest names.
 *
 * @param {object} digests - The map.
 * @param {string} assetsDir - Directory holding the assets.
 * @returns {string[]} One finding per mismatch; empty when they agree.
 */
export const assetFindings = (digests, assetsDir) => {
  const findings = [];
  const expected = MODULES.map((id) => `${id}_bg.wasm.gz`).sort();
  const present = readdirSync(assetsDir)
    .filter((name) => name.endsWith('.wasm.gz'))
    .sort();
  const missing = expected.filter((name) => !present.includes(name));
  const extra = present.filter((name) => !expected.includes(name));
  if (missing.length > 0) findings.push(`missing release assets: ${missing.join(', ')}`);
  if (extra.length > 0) findings.push(`unexpected release assets: ${extra.join(', ')}`);
  for (const id of MODULES) {
    const name = `${id}_bg.wasm.gz`;
    if (!present.includes(name)) continue;
    const gzip = readFileSync(join(assetsDir, name));
    const entry = digests?.[id];
    if (!same(entry?.gzip, describeFile(gzip))) {
      findings.push(
        `${name}: ${JSON.stringify(describeFile(gzip))} differs from the map's ${JSON.stringify(entry?.gzip)}`,
      );
      continue;
    }
    let wasm;
    try {
      wasm = gunzipSync(gzip);
    } catch (error) {
      findings.push(`${name} does not decompress: ${error instanceof Error ? error.message : String(error)}`);
      continue;
    }
    if (!same(entry?.wasm, describeFile(wasm))) {
      findings.push(`${name} decompresses to ${JSON.stringify(describeFile(wasm))}, not the map's wasm`);
    }
  }
  return findings;
};
